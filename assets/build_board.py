"""Bundle the supplied SVG renderer for the live dashboard and offline exports.

The original package remains unchanged in board_src. No JS packages are needed.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "board_src" / "src"
OUTPUT = ROOT / "avalon" / "dashboard" / "static" / "board.js"


def build():
    parts = []
    for name in ("castle-data.mjs", "detail-data.mjs", "avalon-assets.mjs"):
        source = (SOURCE / name).read_text()
        for line in ("import { CASTLE } from './castle-data.mjs';\n",
                     "import { DETAILS } from './detail-data.mjs';\n"):
            source = source.replace(line, "")
        source = source.replace("export const ", "const ").replace("export function ", "function ")
        parts.append(source)
    output = "// Generated by assets/build_board.py from the supplied Avalon SVG package.\n"
    output += "const AvalonBoard = (() => {\n\"use strict\";\n" + "\n".join(parts)
    output += "\nreturn Object.freeze({ renderBoard });\n})();\n"
    OUTPUT.write_text(output)
    print(OUTPUT)


if __name__ == "__main__":
    build()
